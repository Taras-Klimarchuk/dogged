import { Body, Controller, Post } from '@nestjs/common';
import { ApiCreatedResponse, ApiOperation, ApiTags } from '@nestjs/swagger';
import { OrdersService } from './orders.service.js';
import { CreateOrderDto } from './create-order.dto.js';
import { OrderResponseDto } from './order-response.dto.js';

@ApiTags('orders')
@Controller('orders')
export class OrdersController {
  constructor(private readonly ordersService: OrdersService) {}

  @Post()
  @ApiOperation({
    summary:
      'Place an order. Forwards to orders-management through retry + circuit breaker; ' +
      'the idempotencyKey must be generated by the original caller so retries never create duplicates.',
  })
  @ApiCreatedResponse({ type: OrderResponseDto })
  placeOrder(@Body() order: CreateOrderDto): Promise<OrderResponseDto> {
    return this.ordersService.placeOrder(order);
  }
}
